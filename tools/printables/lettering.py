"""Original single-stroke alphabet. Coordinates are authored here, not traced.

One em is 1 high; lowercase x-height is .64 em. Open loops, curved sampled
strokes, gentle per-letter tilt, and pressure variation give readable handwriting.
No font files or third-party lettering are used for any handwritten content.
"""
import math

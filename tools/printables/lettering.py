def width(character):
    if character == ' ':
        return .36
    return max(point[0] for stroke in GLYPHS[character] for point in stroke) + .18


def smooth(path):
    """Round penned curves with a local Catmull-Rom spline; retain straight stems."""
    if len(path) < 4:
        return path
    result = []
    padded = [path[0]] + path + [path[-1]]
    for i in range(1, len(padded)-2):
        p0, p1, p2, p3 = padded[i-1:i+3]
        for step in range(8):
            t = step / 8
            result.append(tuple(.5 * (2*p1[k] + (-p0[k]+p2[k])*t
                + (2*p0[k]-5*p1[k]+4*p2[k]-p3[k])*t*t
                + (-p0[k]+3*p1[k]-3*p2[k]+p3[k])*t*t*t) for k in (0, 1)))
    return result + [path[-1]]


def strokes(text, size, seed, slant=.10):
    rng = random.Random(seed)
    pen = 0
    result = []
    for char in text:
        if char != ' ':
            offset = rng.uniform(-.019, .019)
            stretch = rng.uniform(.975, 1.025)
            for stroke in GLYPHS[char]:
                if char in 'abcdeghmnopqrsuy0235689BCDGOPQRSU':
                    stroke = smooth(stroke)
                result.append([(size * (pen + x + slant * (1 - y)),
                                size * (y * stretch + offset)) for x, y in stroke])
        pen += width(char)
    return result, pen * size

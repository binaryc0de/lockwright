def loop(cx, cy, rx, ry, start=0, end=2 * math.pi):
    return [(cx + rx * math.cos(start + (end - start) * i / 24),
             cy + ry * math.sin(start + (end - start) * i / 24)) for i in range(25)]


def paths(value):
    return [[tuple(map(float, point.split(','))) for point in stroke.split()]
            for stroke in value.split('|')]


